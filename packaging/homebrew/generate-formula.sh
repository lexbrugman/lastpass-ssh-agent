#!/bin/sh
# Emit a Homebrew formula that installs the released binaries.
#
#   generate-formula.sh <version> <owner/repo> <dir-with-release-artifacts>
#
# The artifact directory must hold the .sha256 file build-release.yml writes
# beside each archive. Run after the release is published: publish-homebrew-
# formula.yml downloads those checksums from the release itself, so the hashes
# in the formula are of the files users actually fetch.
set -eu

version="$1"
repo="$2"
artifacts="$3"
base="https://github.com/${repo}/releases/download/v${version}"

# Read every checksum up front: a command substitution inside the heredoc
# below cannot abort this script, so a missing file there would silently
# yield a formula with an empty sha256.
sha() {
    file="${artifacts}/lastpass-ssh-agent-$1.tar.xz.sha256"
    if [ ! -s "$file" ]; then
        echo "missing or empty checksum for $1: $file" >&2
        exit 1
    fi
    # the file holds "<hash> *<name>" — take only the hash
    hash="$(awk '{print $1; exit}' "$file")"
    # The hash is spliced into the sed program below, and the file is whatever
    # the release holds: anything but a bare sha256 could end the substitution
    # and add commands of its own.
    if ! printf '%s\n' "$hash" | grep -qxE '[0-9a-f]{64}'; then
        echo "not a sha256 for $1: $file" >&2
        exit 1
    fi
    # The hash is picked by this file's name and used for that archive's URL,
    # so the line has to be about that archive: a checksum file holding
    # another target's line verifies fine and yields a formula whose hash
    # does not match its download.
    if [ "$(awk '{print $2; exit}' "$file")" != "*lastpass-ssh-agent-$1.tar.xz" ]; then
        echo "checksum for $1 names another file: $file" >&2
        exit 1
    fi
    printf '%s\n' "$hash"
}

macos_arm="$(sha aarch64-apple-darwin)"
macos_intel="$(sha x86_64-apple-darwin)"
linux_arm="$(sha aarch64-unknown-linux-musl)"
linux_intel="$(sha x86_64-unknown-linux-musl)"

# The template is a quoted heredoc: nothing in it is expanded, so backticks
# in the caveats cannot run as commands and $VAR cannot leak the builder's
# environment into a published formula. Values are substituted afterwards.
cat <<'FORMULA' | sed \
    -e "s|@VERSION@|${version}|g" \
    -e "s|@REPO@|${repo}|g" \
    -e "s|@BASE@|${base}|g" \
    -e "s|@MACOS_ARM@|${macos_arm}|g" \
    -e "s|@MACOS_INTEL@|${macos_intel}|g" \
    -e "s|@LINUX_ARM@|${linux_arm}|g" \
    -e "s|@LINUX_INTEL@|${linux_intel}|g"
# Generated by packaging/homebrew/generate-formula.sh — do not edit by hand.
class LastpassSshAgent < Formula
  desc "SSH agent backed by the LastPass CLI: keys never persist on disk"
  homepage "https://github.com/@REPO@"
  version "@VERSION@"
  license "MIT"

  depends_on "lastpass-cli"

  # The dev track. `brew install --HEAD` builds the dev branch from source,
  # which is why rust is a build dependency here and nowhere else: a release
  # install unpacks a prebuilt binary and needs no compiler.
  head do
    url "https://github.com/@REPO@.git", branch: "dev"
    depends_on "rust" => :build
  end

  on_macos do
    on_arm do
      url "@BASE@/lastpass-ssh-agent-aarch64-apple-darwin.tar.xz"
      sha256 "@MACOS_ARM@"
    end
    on_intel do
      url "@BASE@/lastpass-ssh-agent-x86_64-apple-darwin.tar.xz"
      sha256 "@MACOS_INTEL@"
    end
  end

  on_linux do
    on_arm do
      url "@BASE@/lastpass-ssh-agent-aarch64-unknown-linux-musl.tar.xz"
      sha256 "@LINUX_ARM@"
    end
    on_intel do
      url "@BASE@/lastpass-ssh-agent-x86_64-unknown-linux-musl.tar.xz"
      sha256 "@LINUX_INTEL@"
    end
  end

  def install
    if build.head?
      system "cargo", "install", *std_cargo_args
    else
      bin.install "lastpass-ssh-agent"
    end
  end

  # `brew services start lastpass-ssh-agent` installs this as a launchd user
  # agent on macOS and a systemd user unit on Linux — same declaration, both
  # platforms. std_service_path_env puts Homebrew's bin on PATH so the agent
  # can find lpass, which a bare launchd/systemd environment would not.
  # The log names the keys and when each one signs, and the service manager
  # creates it readable by everyone: the agent's own umask never applies to a
  # file opened before it runs. So it lives in a directory only its owner can
  # enter, made here because `brew services` would otherwise create a missing
  # one itself, open to all. A log beside the other formulae's, where the
  # service wrote before it had a directory, keeps its history and loses its
  # other readers — the file itself, not whatever a link there points at.
  def post_install
    log_dir = var/"log/lastpass-ssh-agent"
    odie "#{log_dir} is a symlink; the service log needs a directory of its own" if log_dir.symlink?
    log_dir.mkpath
    log_dir.chmod 0700
    shared = var/"log/lastpass-ssh-agent.log"
    shared.chmod 0600 if shared.file? && !shared.symlink?
  end

  service do
    run [opt_bin/"lastpass-ssh-agent", "start"]
    keep_alive true
    log_path var/"log/lastpass-ssh-agent/agent.log"
    error_log_path var/"log/lastpass-ssh-agent/agent.log"
    environment_variables PATH: std_service_path_env
  end

  def caveats
    <<~EOS
      Log in to LastPass first, then check the setup:

        lpass login you@example.com
        lastpass-ssh-agent doctor

      Run it in the background (launchd on macOS, systemd --user on Linux):

        brew services start lastpass-ssh-agent

      It restarts at every login. Homebrew does not restart services on
      upgrade, so after `brew upgrade` the old binary keeps serving until you
      do:

        brew services restart lastpass-ssh-agent

      Do NOT use `sudo brew services`: a system daemon has no GUI session, so
      every confirmation fails closed and nothing is ever signed.

      On Linux, a --user service runs only while you have a session
      (`loginctl enable-linger "$USER"` keeps it up without one), and the
      default "tty" confirmation has no terminal. Set a helper in
      ~/.config/lastpass-ssh-agent/config.toml before starting it:

        confirm = "askpass"
        askpass = "/usr/bin/ssh-askpass"

      Point SSH at the agent. The socket path differs per platform, so ask:

        lastpass-ssh-agent env

      and put that path in ~/.ssh/config, remembering that IdentityAgent
      overrides SSH_AUTH_SOCK for the hosts it matches:

        Host *
            IdentityAgent "<the path printed above>"

      There is a dev track (`brew install --HEAD`), which builds from source
      and does not move forward on a plain `brew upgrade`. Switching either
      way is documented at:

        https://github.com/@REPO@#following-the-dev-branch
    EOS
  end

  test do
    # A release install must report exactly the version the formula claims —
    # a mismatch there means the formula and the binary came from different
    # builds. A head install cannot: brew calls it HEAD-<sha> while the binary
    # describes itself against the newest release tag it can see, so check the
    # name instead. Decided from `version` rather than `build`, which is not
    # dependable in a test.
    expected = if version.to_s.start_with?("HEAD")
      "lastpass-ssh-agent"
    else
      version.to_s
    end
    assert_match expected, shell_output("#{bin}/lastpass-ssh-agent --version")
    # doctor exits nonzero without a LastPass login, but must still run
    assert_match "lpass", shell_output("#{bin}/lastpass-ssh-agent doctor 2>&1", 1)
  end
end
FORMULA
